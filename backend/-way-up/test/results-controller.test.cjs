const assert = require("node:assert/strict");
const test = require("node:test");
const {
  ResultsController,
  ShareController,
} = require("../dist/results/results.controller.js");
const { PdfService } = require("../dist/results/pdf.service.js");

test("GET /results returns the items array expected by the frontend", async () => {
  const items = [{ id: "result-1", archetype: { name: "Twórca" } }];
  const service = { list: async (userId) => (userId === "user-1" ? items : []) };
  const controller = new ResultsController(service, {}, {});

  assert.deepEqual(await controller.getResults({ id: "user-1" }), { items });
});

test("POST /results/:id/share returns the shareToken field expected by the frontend", async () => {
  const service = { share: async () => "share-token" };
  const controller = new ResultsController(service, {}, {});

  assert.deepEqual(await controller.shareResult({ id: "user-1" }, "result-1"), {
    shareToken: "share-token",
  });
});

test("PDF download sets private PDF headers and sends the generated bytes", async () => {
  const pdfBuffer = Buffer.from("%PDF-1.7");
  const service = { generateProfilePdf: async () => pdfBuffer };
  const controller = new ResultsController({}, {}, service);
  const response = {
    headers: null,
    body: null,
    set(headers) {
      this.headers = headers;
      return this;
    },
    end(body) {
      this.body = body;
    },
  };

  await controller.downloadPdf({ id: "user-1" }, "result-1", response);

  assert.equal(response.headers["Content-Type"], "application/pdf");
  assert.equal(response.headers["Cache-Control"], "private, no-store");
  assert.deepEqual(response.body, pdfBuffer);
});

test("PDF service generates a report using the bundled font files", async () => {
  const service = new PdfService({
    findOwned: async () => ({
      profile: {
        archetype: { name: "Twórca", tagline: "Projektuje nowe rozwiązania." },
        paths: [],
        skills: { hard: [], soft: [] },
        explanation: "Masz potencjał do rozwijania pomysłów.",
      },
    }),
  });

  const pdfBuffer = await service.generateProfilePdf("user-1", "result-1");

  assert.equal(pdfBuffer.subarray(0, 5).toString(), "%PDF-");
  assert.ok(pdfBuffer.length > 1000);
});

test("PDFDocument accepts a bundled font file instead of built-in Helvetica", () => {
  const PDFDocument = require("pdfkit");
  const path = require("node:path");
  const fontPath = path.join(__dirname, "..", "fonts", "Roboto-Regular.ttf");
  const doc = new PDFDocument({ autoFirstPage: false, font: fontPath });

  assert.equal(doc._fontSource, fontPath);
  assert.equal(doc._font.name, "Roboto-Regular");
});

test("public shared result uses the results service card", async () => {
  const card = { archetype: { name: "Twórca" }, paths: [] };
  const service = { publicCard: async (token) => (token === "share-token" ? card : null) };
  const controller = new ShareController(service);

  assert.deepEqual(await controller.getSharedResult("share-token"), card);
});
